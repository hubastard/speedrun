it('Sign up, sign in, onboarding', () => {
  cy.visit('/signup')
  cy.get('#firstName').type('Bob')
  cy.get('#lastName').type('Ross')
  cy.get('#username').type('PainterJoy90')
  cy.get('#password').type('s3cret')
  cy.get('#confirmPassword').type('s3cret')
  cy.get('[data-test=signup-submit]').click()
  cy.contains('h1', 'Sign in').should('be.visible')
  cy.get('#username').type('PainterJoy90')
  cy.get('#password').type('s3cret')
  cy.get('[data-test=signin-submit]').click()
  cy.contains('Get Started with Real World App').should('be.visible')
  cy.get('[data-test=user-onboarding-next]').click()
  cy.contains('Create Bank Account').should('be.visible')
  cy.get('#bankaccount-bankName-input').type('The Best Bank')
  cy.get('#bankaccount-routingNumber-input').type('987654321')
  cy.get('#bankaccount-accountNumber-input').type('123456789')
  cy.contains('button', 'Save').click()
  cy.contains('Finished').should('be.visible')
  cy.get('[data-test=user-onboarding-next]').click()
  cy.contains('Finished').should('not.exist')
  cy.get('[data-test=sidenav-signout]').click()
  cy.get('#username').should('be.visible')
})

